describe('cursor baton-handoff rule (U8)', () => {
  it('baton-handoff.mdc sets alwaysApply: true and its body is <=5 non-empty lines', () => {
    assert.ok(existsSync(RULE_MDC), miss(RULE_MDC, 'the baton-handoff Cursor rule'));
    const md = readFileSync(RULE_MDC, 'utf8');
    const fm = frontmatter(md);
    assert.ok(fm, '.mdc has YAML frontmatter');
    assert.match(fm, /(^|\n)alwaysApply:\s*true\b/, 'the rule sets alwaysApply: true');

    const body = md.replace(/^---\n[\s\S]*?\n---/, '');
    const bodyLines = body.split('\n').map((l) => l.trim()).filter((l) => l.length > 0);
    assert.ok(bodyLines.length <= 5, `the rule body must be <=5 non-empty lines (got ${bodyLines.length})`);
  });
});

