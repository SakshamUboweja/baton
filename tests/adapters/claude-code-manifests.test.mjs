const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..');
const ADAPTER_DIR = join(repoRoot, 'adapters', 'claude-code');
const PLUGIN_DIR = join(repoRoot, '.claude-plugin');
const PLUGIN_JSON = join(PLUGIN_DIR, 'plugin.json');
const MARKETPLACE_JSON = join(PLUGIN_DIR, 'marketplace.json');
const COMMANDS_DIR = join(ADAPTER_DIR, 'commands');
const SKILL_MD = join(ADAPTER_DIR, 'skills', 'handoff-protocol', 'SKILL.md');

const miss = (p, who) => `${p} must exist — the ADAPTERS wave implementer authors ${who} here`;

// Mirrors tests/invariants/attribution.test.mjs VERBATIM (narrow by design —
// never trips on real platform/model identifiers or the sole-author name).
const ATTRIBUTION_PATTERNS = [
  /co-authored-by/i,
  /generated with claude/i,
  /generated by claude/i,
  /🤖/,
  /written by (an? )?ai\b/i,
  /authored by (an? )?ai\b/i,
  /powered by claude/i,
];
const scanAttribution = (text) => ATTRIBUTION_PATTERNS.filter((re) => re.test(text)).map((re) => re.source);

/** @param {string} dir */
function walkFiles(dir) {
  /** @type {string[]} */
  const out = [];
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walkFiles(p));
    else out.push(p);
  }
  return out;
}

/** Extract the YAML frontmatter block (text between the first two `---` fences). */
function frontmatter(md) {
  const m = md.match(/^---\n([\s\S]*?)\n---/);
  return m ? m[1] : null;
}

// ===========================================================================
describe('claude-code plugin.json (M1)', () => {
  it('lives at repo root, is authored by SakshamUboweja, and overrides component paths into adapters/claude-code/', () => {
    assert.ok(existsSync(PLUGIN_JSON), miss(PLUGIN_JSON, 'the Claude Code plugin manifest'));
    const json = JSON.parse(readFileSync(PLUGIN_JSON, 'utf8'));

    assert.ok(typeof json.name === 'string' && json.name.length > 0, 'plugin.json carries a name');
    assert.equal(json.author?.name, 'SakshamUboweja', 'plugin.json author.name is SakshamUboweja');

    // Path overrides steer components into adapters/claude-code/ (spike result).
    const serialized = JSON.stringify(json);
    assert.ok(serialized.includes('adapters/claude-code'), 'component path overrides point into adapters/claude-code/');
    assert.ok(
      typeof json.hooks === 'string' && json.hooks.includes('adapters/claude-code/hooks'),
      'the hooks override points at adapters/claude-code/hooks/hooks.json',
    );
  });
});

// ===========================================================================
describe('claude-code marketplace.json (M2)', () => {
  it('is a single-entry repo-as-marketplace naming SakshamUboweja', () => {
    assert.ok(existsSync(MARKETPLACE_JSON), miss(MARKETPLACE_JSON, 'the repo-as-marketplace manifest'));
    const json = JSON.parse(readFileSync(MARKETPLACE_JSON, 'utf8'));
    assert.ok(typeof json.name === 'string' && json.name.length > 0, 'marketplace.json carries a name');
    assert.ok(Array.isArray(json.plugins) && json.plugins.length >= 1, 'the marketplace lists at least one plugin (the repo itself)');
    assert.ok(JSON.stringify(json).includes('SakshamUboweja'), 'SakshamUboweja is named as the marketplace owner/plugin author');
  });
});

// ===========================================================================
describe('claude-code command frontmatter (M3)', () => {
  for (const name of ['handoff', 'receive', 'baton-setup']) {
    it(`${name}.md exists and carries a description in frontmatter`, () => {
      const p = join(COMMANDS_DIR, `${name}.md`);
      assert.ok(existsSync(p), miss(p, `the /baton:${name} command`));
      const fm = frontmatter(readFileSync(p, 'utf8'));
      assert.ok(fm, `${name}.md has a YAML frontmatter block`);
      assert.match(fm, /(^|\n)description:\s*\S/, `${name}.md frontmatter declares a description`);
    });
  }

  it('receive.md sets disable-model-invocation: true; handoff.md does NOT', () => {
    const recv = join(COMMANDS_DIR, 'receive.md');
    const hand = join(COMMANDS_DIR, 'handoff.md');
    assert.ok(existsSync(recv), miss(recv, 'the /baton:receive command'));
    assert.ok(existsSync(hand), miss(hand, 'the /baton:handoff command'));

    const recvFm = frontmatter(readFileSync(recv, 'utf8')) ?? '';
    const handFm = frontmatter(readFileSync(hand, 'utf8')) ?? '';
    assert.match(recvFm, /(^|\n)disable-model-invocation:\s*true\b/, 'receive is NOT model-invocable (disable-model-invocation: true)');
    assert.doesNotMatch(handFm, /(^|\n)disable-model-invocation:\s*true\b/, 'handoff IS model-invocable (so Claude can propose it near limits)');
  });
});

// ===========================================================================
describe('claude-code handoff-protocol skill (M4)', () => {
  it('skills/handoff-protocol/SKILL.md exists with a name + description', () => {
    assert.ok(existsSync(SKILL_MD), miss(SKILL_MD, 'the handoff-protocol skill'));
    const fm = frontmatter(readFileSync(SKILL_MD, 'utf8'));
    assert.ok(fm, 'SKILL.md has YAML frontmatter');
    assert.match(fm, /(^|\n)name:\s*handoff-protocol\b/, 'SKILL.md declares name: handoff-protocol');
    assert.match(fm, /(^|\n)description:\s*\S/, 'SKILL.md declares a description');
  });

  it('(V3) the continuation path is a SKILL, not an agent — no v1 handoff agent surface exists', () => {
    // Anchored on the two red files so this test cannot pass vacuously against
    // the empty tree: the skill and the manifest must exist FIRST.
    assert.ok(existsSync(SKILL_MD), miss(SKILL_MD, 'the handoff-protocol skill'));
    assert.ok(existsSync(PLUGIN_JSON), miss(PLUGIN_JSON, 'the Claude Code plugin manifest'));

    // No handoff-named agent definition ships under the adapter's agents/ dir.
    const agentFiles = walkFiles(join(ADAPTER_DIR, 'agents')).map((f) => relative(repoRoot, f));
    assert.deepEqual(
      agentFiles.filter((f) => /handoff/i.test(f)),
      [],
      'no handoff agent ships in v1 (the main thread must inherit the task; handoff-verifier agent is out of v1 scope)',
    );

    // And plugin.json exposes no agents override naming a handoff agent.
    const json = JSON.parse(readFileSync(PLUGIN_JSON, 'utf8'));
    const agentsOverride = JSON.stringify(json.agents ?? null);
    assert.doesNotMatch(agentsOverride, /handoff/i, 'plugin.json must not expose a handoff agent via an agents override');
  });
});

// ===========================================================================
describe('claude-code adapter — zero-attribution scan (M5)', () => {
  it('no file in adapters/claude-code/** or .claude-plugin/ carries an AI-credit string', () => {
    assert.ok(existsSync(ADAPTER_DIR), miss(ADAPTER_DIR, 'the Claude Code adapter surface'));
    const files = [...walkFiles(ADAPTER_DIR), ...walkFiles(PLUGIN_DIR)];
    assert.ok(files.length > 0, 'the Claude Code adapter surface must yield files to scan (non-vacuous)');
    for (const f of files) {
      assert.deepEqual(scanAttribution(readFileSync(f, 'utf8')), [], `${relative(repoRoot, f)} must carry no attribution string`);
    }
  });

  it('positive control: the scanner has teeth', () => {
    // Deliberately the ONLY test in this wave that passes against the empty
    // tree: it pins the SCANNER (the test instrument), not any adapter file, so
    // it cannot green the wave vacuously — the sibling scan arm above stays red
    // until adapters/claude-code/** exists AND is clean. Same convention as the
    // committed positive control in tests/invariants/attribution.test.mjs.
    assert.ok(scanAttribution('Co-Authored-By: Claude').length > 0);
    assert.ok(scanAttribution('🤖 Generated with Claude Code').length > 0);
  });
});
