describe('codex adapter — zero-attribution scan (C6)', () => {
  it('no file under adapters/codex/** carries an AI-credit string', () => {
    assert.ok(existsSync(ADAPTER_DIR), miss(ADAPTER_DIR, 'the Codex adapter surface'));
    const files = walkFiles(ADAPTER_DIR);
    assert.ok(files.length > 0, 'the Codex adapter surface must yield files to scan (non-vacuous)');
    for (const f of files) {
      assert.deepEqual(scanAttribution(readFileSync(f, 'utf8')), [], `${relative(repoRoot, f)} must carry no attribution string`);
    }
  });
});
