describe('codex baton-handoff skill (C5)', () => {
  it('.agents/skills/baton-handoff/SKILL.md exists with a name + description', () => {
    assert.ok(existsSync(SKILL_MD), miss(SKILL_MD, 'the Codex baton-handoff skill'));
    const md = readFileSync(SKILL_MD, 'utf8');
    const m = md.match(/^---\n([\s\S]*?)\n---/);
    assert.ok(m, 'SKILL.md has YAML frontmatter');
    assert.match(m[1], /(^|\n)name:\s*baton-handoff\b/, 'SKILL.md declares name: baton-handoff');
    assert.match(m[1], /(^|\n)description:\s*\S/, 'SKILL.md declares a description');
  });
});

